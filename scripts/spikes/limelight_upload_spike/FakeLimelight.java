    static void wireCheck(byte[] doc, String what) throws Exception {
        Validator v = wire.newValidator();
        v.setProperty(XMLConstants.ACCESS_EXTERNAL_DTD, "");
        v.setProperty(XMLConstants.ACCESS_EXTERNAL_SCHEMA, "");
        try {
            v.validate(new StreamSource(new ByteArrayInputStream(doc)));
        } catch (SAXParseException e) {
            throw new IllegalStateException("WIRE " + what + " does not match the importer's JAXB wire schema: " + e.getMessage());
        }
    }

    static String xml(String root, Map<String, String> given) throws Exception {
        Map<String, String> attrs = new LinkedHashMap<>();
        for (String r : REQUIRED.getOrDefault(root, new String[0])) attrs.put(r, r.equals("maxSize") ? "0" : "false");
        attrs.putAll(given);
        StringBuilder sb = new StringBuilder("<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>\n<").append(root);
        attrs.forEach((k, v) -> sb.append(' ').append(k).append("=\"").append(esc(v)).append('"'));
        String out = sb.append("/>\n").toString();
        wireCheck(out.getBytes(StandardCharsets.UTF_8), "response " + root);
        return out;
    }

    static String esc(String s) {
        return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;");
    }

    static void writeState() throws IOException {
        Map<String, Object> s = new LinkedHashMap<>();
        s.put("uploads", new ArrayList<>(uploads.values()));
        s.put("requests", events.size());
        Path tmp = stateFile.resolveSibling(stateFile.getFileName() + ".tmp");
        Files.writeString(tmp, json(s));
        Files.move(tmp, stateFile, java.nio.file.StandardCopyOption.REPLACE_EXISTING, java.nio.file.StandardCopyOption.ATOMIC_MOVE);
    }

    @SuppressWarnings("unchecked")
    static String json(Object o) {
        if (o == null) return "null";
        if (o instanceof String s) {
            StringBuilder sb = new StringBuilder("\"");
            for (char c : s.toCharArray()) {
                if (c == '"' || c == '\\') sb.append('\\').append(c);
                else if (c < 0x20) sb.append(String.format("\\u%04x", (int) c));
                else sb.append(c);
            }
            return sb.append('"').toString();
        }
        if (o instanceof Number || o instanceof Boolean) return o.toString();
        if (o instanceof Map<?, ?> m) {
            StringBuilder sb = new StringBuilder("{"); boolean first = true;
            for (Map.Entry<?, ?> e : m.entrySet()) { if (!first) sb.append(','); first = false;
                sb.append(json(String.valueOf(e.getKey()))).append(':').append(json(e.getValue())); }
            return sb.append('}').toString();
        }
        if (o instanceof List<?> l) {
            StringBuilder sb = new StringBuilder("["); boolean first = true;
            for (Object x : l) { if (!first) sb.append(','); first = false; sb.append(json(x)); }
            return sb.append(']').toString();
        }
        return json(o.toString());
    }

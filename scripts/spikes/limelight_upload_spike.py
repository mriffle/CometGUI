def s_leak(ctx):
    S = "leak"
    kb = ctx["key"].encode()
    found = []
    for d, _, fs in os.walk(RUN):
        for f in fs:
            p = os.path.join(d, f)
            if kb in open(p, "rb").read():
                found.append(os.path.relpath(p, RUN))
    fact("leak.files_holding_the_key", sorted(found))
    allowed = {"key", "importer-argv.jfr"}
    check(S, "the key is only in its own file and in the JFR recording of the argv run (JFR records java arguments)",
          set(found) <= allowed and "key" in found, str(sorted(found)))
    if "argv_jfr" in ctx:
        check(S, "argv leaks onward: the argv run's JFR recording holds the full key", "importer-argv.jfr" in found)



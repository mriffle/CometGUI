def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", help="comma-separated section names (prerequisites are added)")
    ap.add_argument("--fake-source", help="run an INJURED copy of FakeLimelight.java (falsifiability demonstrations)")
    a = ap.parse_args()
    if a.fake_source:
        FAKE_SOURCE[0] = os.path.abspath(a.fake_source)
        print(f"!!   using injected fake {FAKE_SOURCE[0]}")
    want = [s for s, _ in SECTIONS]
    if a.only:
        sel = set(a.only.split(","))
        unknown = sel - set(want)
        if unknown:
            sys.exit(f"unknown section(s): {sorted(unknown)}")
        for s in list(sel):
            sel |= set(NEEDS.get(s, []))
        want = [s for s in want if s in sel]
    t0 = time.time()
    shutil.rmtree(RUN, ignore_errors=True)
    os.makedirs(RUN)
    key = "LL" + secrets.token_urlsafe(24)  # seeded; never printed by this script
    key_file = os.path.join(RUN, "key")

class Abort(Exception):
    pass


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def java():
    jh = os.environ.get("JAVA_HOME")
    if not jh:
        raise Abort("JAVA_HOME unset: run '. tools/env.sh' first")
    return os.path.join(jh, "bin", "java")


def jdk_tool(name):
    return os.path.join(os.environ["JAVA_HOME"], "bin", name)


def run(cmd, stdin_bytes=None, timeout=300, env=None, cwd=None):
    p = subprocess.run(cmd, input=stdin_bytes, capture_output=True, timeout=timeout, env=env, cwd=cwd or ROOT)
    return p.returncode, p.stdout.decode("utf-8", "replace"), p.stderr.decode("utf-8", "replace")


def jfr_sockets(jfr_file):
    """[(event, address, port)] for every SocketRead/SocketWrite in a recording."""
    rc, out, err = run([jdk_tool("jfr"), "print", "--json", "--events", "jdk.SocketRead,jdk.SocketWrite", jfr_file])
    if rc != 0:
        raise Abort(f"jfr print failed: {err}")
    evs = json.loads(out)["recording"]["events"]
    return [(e["type"], e["values"]["address"], e["values"]["port"]) for e in evs]



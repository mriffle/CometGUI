def sample_proc(pid, key, stop, seen):
    kb = key.encode()
    while not stop.is_set():
        try:
            cmd = open(f"/proc/{pid}/cmdline", "rb").read()
            env = open(f"/proc/{pid}/environ", "rb").read()
            seen["samples"] += 1
            seen["argv"] |= kb in cmd
            seen["env"] |= kb in env
        except OSError:
            pass
        time.sleep(0.05)


def run_observed(cmd, key, stdin_bytes=None, timeout=300):
    """Run a child, sampling /proc/<pid>/{cmdline,environ} for the key while it runs."""
    p = subprocess.Popen(cmd, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE, cwd=ROOT)
    seen = {"samples": 0, "argv": False, "env": False}
    stop = threading.Event()
    t = threading.Thread(target=sample_proc, args=(p.pid, key, stop, seen))
    t.start()
    out, err = p.communicate(input=stdin_bytes, timeout=timeout)
    stop.set()
    t.join()
    return p.returncode, out.decode("utf-8", "replace"), err.decode("utf-8", "replace"), seen



def scan(root, own):
    netrefs, urls, analytics = [], {}, []
    for d, _, fs in os.walk(root):
        for f in fs:
            p = os.path.join(d, f)
            rel = os.path.relpath(p, root)
            b = open(p, "rb").read()
            mine = rel.startswith(own)
            if mine and f.endswith(".class") and NET.search(b):
                netrefs.append(rel)
            if mine:
                for u in URL.findall(b):
                    urls.setdefault(u.decode("latin1"), []).append(rel)
            if ANALYTICS.search(b):
                analytics.append(rel)
    return sorted(netrefs), urls, sorted(analytics)



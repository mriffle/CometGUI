class Fake:
    def __init__(self, tag, key_file, xsd, wire, hold_ms=0):
        self.dir = os.path.join(RUN, "fake-" + tag)
        os.makedirs(self.dir, exist_ok=True)
        self.log = os.path.join(self.dir, "fake.log")
        self.state = os.path.join(self.dir, "state.json")
        cmd = [java(), FAKE_SOURCE[0], "--xsd", xsd, "--wire-xsd", wire,
               "--key-file", key_file, "--project", PROJECT, "--store", os.path.join(self.dir, "store"),
               "--log", self.log, "--state", self.state]
        if hold_ms:
            cmd += ["--hold-auth-ms", str(hold_ms)]
        self.out = open(os.path.join(self.dir, "fake.stdout"), "w")
        self.p = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=self.out, text=True, cwd=ROOT)
        line = self.p.stdout.readline()
        if not line.startswith("FAKE-LISTENING "):
            raise Abort(f"fake did not start: {line!r}")
        self.url = line.split()[1]
        self.port = int(re.search(r":(\d+)/", self.url).group(1))

    def events(self):
        if not os.path.exists(self.log):
            return []
        return [json.loads(l) for l in open(self.log)]

    def uploads(self):
        return json.load(open(self.state))["uploads"]

    def stop(self):
        self.p.terminate()
        try:
            self.p.wait(10)
        except subprocess.TimeoutExpired:
            self.p.kill()
        self.out.close()



class Sinkhole:
    """A loopback 'proxy' that records the first request line and answers 403."""

    def __init__(self):
        self.lines = []
        self.s = socket.socket()
        self.s.bind(("127.0.0.1", 0))
        self.s.listen(16)
        self.port = self.s.getsockname()[1]
        self.t = threading.Thread(target=self.loop, daemon=True)
        self.t.start()

    def loop(self):
        while True:
            try:
                c, _ = self.s.accept()
            except OSError:
                return
            c.settimeout(5)
            try:
                self.lines.append(c.recv(65536).split(b"\r\n", 1)[0].decode("latin1"))
                c.sendall(b"HTTP/1.1 403 Forbidden\r\nContent-Length: 0\r\nConnection: close\r\n\r\n")
            except OSError:
                pass
            c.close()

    def close(self):
        self.s.close()


